export const url = pgTable(
  "url",
  {
    id: serial("id").primaryKey(),
    alias: varchar("alias", { length: 52 }).notNull().unique(),
    originalUrl: text("original_url").notNull(),
    isCustomAlias: boolean("is_custom_alias").default(false).notNull(),
    userId: text("user_id").references(() => user.id, { onDelete: "cascade" }),
    expiresAt: timestamp("expires_at"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
  },
  (table) => [
    index("url_alias_idx").on(table.alias),
    index("url_userId_idx").on(table.userId),
    index("url_expiresAt_idx").on(table.expiresAt),
  ],
);

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  urls: many(url),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));

export const urlRelations = relations(url, ({ one }) => ({
  user: one(user, {
    fields: [url.userId],
    references: [user.id],
  }),
}));

export type Url = typeof url.$inferSelect;
export type NewUrl = typeof url.$inferInsert;
